//Variables in Java
public class Variables {
    public static void main(String[] args) {
        int a = 10;
        int b = 5;
        System.out.println("a");
        System.out.println(a);                   //To get the value of given variable 'a' we should not use double qoutes or it will print whatever is assigned in "" only.
        b= 50 ;
        a = 9;
        System.out.println(a);
        System.out.println(b);
        String name = "Batman";                 //String should be assigned with double qoutes.
        System.out.println(name);
    }
    
}
